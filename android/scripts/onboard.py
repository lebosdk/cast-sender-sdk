def _windows_input_dialog(title: str, prompt: str, secret: bool) -> str:
    powershell = None
    for candidate in ("powershell.exe", "powershell", "pwsh.exe", "pwsh"):
        powershell = shutil.which(candidate)
        if powershell:
            break
    if not powershell:
        raise DialogUnavailable("Windows PowerShell is unavailable")

    script = _windows_dialog_script(title, prompt, secret)
    encoded = base64.b64encode(script.encode("utf-16le")).decode("ascii")
    result = subprocess.run(
        [
            powershell,
            "-NoLogo",
            "-NoProfile",
            "-NonInteractive",
            "-STA",
            "-WindowStyle",
            "Hidden",
            "-EncodedCommand",
            encoded,
        ],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        encoding="utf-8",
        errors="replace",
        creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
        check=False,
    )
    if result.returncode == 0:
        return result.stdout.lstrip("\ufeff").rstrip("\r\n")
    if result.returncode == 2:
        raise DialogCancelled()
    raise DialogUnavailable(result.stderr.strip() or "the Windows dialog failed")


def _linux_input_dialog(title: str, prompt: str, secret: bool) -> str:
    zenity = shutil.which("zenity")
    if zenity:
        command = [
            zenity,
            "--entry",
            "--title=" + title,
            "--text=" + prompt,
            "--ok-label=继续 / Continue",
            "--cancel-label=取消 / Cancel",
        ]
        if secret:
            command.append("--hide-text")
    else:
        kdialog = shutil.which("kdialog")
        if not kdialog:
            raise DialogUnavailable("neither zenity nor kdialog is available")
        command = [
            kdialog,
            "--password" if secret else "--inputbox",
            prompt,
            "--title",
            title,
            "--ok-label",
            "继续 / Continue",
            "--cancel-label",
            "取消 / Cancel",
        ]
    result = subprocess.run(
        command,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        check=False,
    )
    if result.returncode == 0:
        return result.stdout.rstrip("\r\n")
    if result.returncode == 1:
        raise DialogCancelled()
    raise DialogUnavailable(result.stderr.strip() or "the Linux dialog failed")


def _tk_input_dialog(title: str, prompt: str, secret: bool) -> str:
    try:
        import tkinter
        from tkinter import simpledialog
    except ImportError as exc:
        raise DialogUnavailable("tkinter is unavailable") from exc
    root = None
    try:
        root = tkinter.Tk()
        root.withdraw()
        root.attributes("-topmost", True)
        root.update()
        options = {"parent": root}
        if secret:
            options["show"] = "*"
        value = simpledialog.askstring(title, prompt, **options)
    except tkinter.TclError as exc:
        raise DialogUnavailable(str(exc)) from exc
    finally:
        if root is not None:
            root.destroy()
    if value is None:
        raise DialogCancelled()
    return value


def _terminal_input(title: str, prompt: str, secret: bool) -> str:
    print(
        "图形输入不可用，将在当前终端继续。\n"
        "Graphical input is unavailable; continuing in the current terminal for " + title + ".",
        file=sys.stderr,
    )
    try:
        if secret:
            with warnings.catch_warnings():
                warnings.simplefilter("error", getpass.GetPassWarning)
                return getpass.getpass(prompt + "\nInput (hidden): ")
        return input(prompt + "\nInput: ")
    except getpass.GetPassWarning:
        print(
            "警告：当前终端无法隐藏输入，下一个值将在输入时可见。请确保无人查看或录制终端。\n"
            "Warning: this terminal cannot hide the input. The next value will be visible "
            "while you type it; make sure nobody else can see or record the terminal.",
            file=sys.stderr,
        )
        try:
            return input(prompt + "\nInput (visible): ")
        except (EOFError, KeyboardInterrupt) as exc:
            raise OnboardingError(
                "Platform account input was cancelled.", show_fallback=False
            ) from exc
    except (EOFError, KeyboardInterrupt) as exc:
        raise OnboardingError("Platform account input was cancelled.", show_fallback=False) from exc


def _input_dialog(title: str, prompt: str, secret: bool = False) -> str:
    backends = []
    if sys.platform == "darwin":
        backends.append(_macos_input_dialog)
    elif sys.platform == "win32":
        backends.append(_windows_input_dialog)
    elif sys.platform.startswith("linux"):
        backends.append(_linux_input_dialog)
    backends.append(_tk_input_dialog)

    failures = []
    for backend in backends:
        try:
            return backend(title, prompt, secret)
        except DialogCancelled as exc:
            raise OnboardingError("Platform account input was cancelled.", show_fallback=False) from exc
        except DialogUnavailable as exc:
            failures.append(str(exc))
    if failures:
        return _terminal_input(title, prompt, secret)
    raise OnboardingError("No account input method is available.", show_fallback=False)


def _normalize_error_code(value: Any) -> Optional[int]:
    try:
        return int(value)
    except (TypeError, ValueError):
        return None


class OpenPlatformClient:
    def __init__(self, base_url: str, timeout: int = 15) -> None:
        self.base_url = base_url.rstrip("/")
        self.timeout = timeout

    def post(
        self,
        path: str,
        payload: Dict[str, Any],
        token: Optional[str] = None,
    ) -> Dict[str, Any]:
        url = self.base_url + path
        headers = {"Content-Type": "application/json; charset=utf-8"}
        if token:
            headers["token"] = token
        http_request = request.Request(
            url,
            data=json.dumps(payload, ensure_ascii=False).encode("utf-8"),
            headers=headers,
            method="POST",
        )
        try:
            with request.urlopen(http_request, timeout=self.timeout) as response:
                status = response.getcode()
                body = response.read().decode("utf-8")
        except error.HTTPError as exc:
            body = exc.read().decode("utf-8", errors="replace")
            api_error = self._parse_error(body, exc.code)
            raise api_error from exc
        except (error.URLError, TimeoutError, OSError) as exc:
            raise ApiError(None, "Network request failed: " + str(exc)) from exc

        try:
            envelope = json.loads(body)
        except json.JSONDecodeError as exc:
            raise ApiError(None, "The platform returned invalid JSON", http_status=status) from exc
        if not isinstance(envelope, dict):
            raise ApiError(None, "The platform returned an invalid response", http_status=status)
        if envelope.get("status") != 1:
            raise ApiError(
                _normalize_error_code(envelope.get("errorCode")),
                str(envelope.get("msg") or "Platform request failed"),
                envelope.get("data") if isinstance(envelope.get("data"), dict) else {},
                status,
            )
        data = envelope.get("data")
        return data if isinstance(data, dict) else {}

    @staticmethod
    def _parse_error(body: str, status: int) -> ApiError:
        try:
            envelope = json.loads(body)
        except json.JSONDecodeError:
            return ApiError(None, "HTTP request failed", http_status=status)
        if not isinstance(envelope, dict):
            return ApiError(None, "HTTP request failed", http_status=status)
        return ApiError(
            _normalize_error_code(envelope.get("errorCode")),
            str(envelope.get("msg") or "HTTP request failed"),
            envelope.get("data") if isinstance(envelope.get("data"), dict) else {},
            status,
        )


def _state_directory() -> Path:
    if os.name == "nt" and os.environ.get("LOCALAPPDATA"):
        return Path(os.environ["LOCALAPPDATA"]) / "hpplay-skill"
    root = Path(os.environ.get("XDG_STATE_HOME", Path.home() / ".local" / "state"))
    return root / "hpplay-skill"


class StateStore:
    def __init__(self, package_name: str, src: str, base_url: str) -> None:
        # Including the endpoint prevents a test token from being reused after release.
        identity = base_url + "\0" + src + "\0" + package_name
        key = hashlib.sha256(identity.encode("utf-8")).hexdigest()[:20]
        self.path = _state_directory() / (key + ".json")

    def load(self) -> Dict[str, Any]:
        if not self.path.exists():
            return {}
        try:
            value = json.loads(self.path.read_text(encoding="utf-8"))
            return value if isinstance(value, dict) else {}
        except (OSError, json.JSONDecodeError):
            return {}

    def save(self, state: Dict[str, Any]) -> None:
        self.path.parent.mkdir(parents=True, exist_ok=True)
        _atomic_write(self.path, json.dumps(state, ensure_ascii=False, indent=2) + "\n")

    def clear(self) -> None:
        try:
            self.path.unlink()
        except FileNotFoundError:
            pass


def _atomic_write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary_name = tempfile.mkstemp(prefix=path.name + ".", dir=str(path.parent))
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            handle.write(content)
        os.chmod(temporary_name, 0o600)
        os.replace(temporary_name, path)
        os.chmod(path, 0o600)
    finally:
        try:
            os.unlink(temporary_name)
        except FileNotFoundError:
            pass


def _git_root(project_dir: Path) -> Optional[Path]:
    result = subprocess.run(
        ["git", "-C", str(project_dir), "rev-parse", "--show-toplevel"],
        stdout=subprocess.PIPE,
        stderr=subprocess.DEVNULL,
        text=True,
        check=False,
    )
    if result.returncode != 0:
        return None
    return Path(result.stdout.strip()).resolve()


def _relative_to(path: Path, parent: Path) -> Optional[Path]:
    try:
        return path.relative_to(parent)
    except ValueError:
        return None


class CredentialsWriter:
    def __init__(
        self,
        project_dir: Path,
        module_dir: Path,
        package_name: str,
        destination: Optional[Path],
    ) -> None:
        self.project_dir = project_dir.resolve()
        self.module_dir = module_dir.resolve()
        self.package_name = package_name
        self.path = (destination or (self.project_dir / "local.properties")).expanduser().resolve()
        self.config_path = (
            self.module_dir
            / "src"
            / "main"
            / "java"
            / Path(*self.package_name.split("."))
            / CONFIG_CLASS_NAME
        )

    def validate_destination(self) -> None:
        project_git_root = _git_root(self.project_dir)
        if project_git_root is None:
            if _relative_to(self.path, self.project_dir) is not None:
                raise OnboardingError(
                    "The project is not in Git. Use --credentials-file with a path outside "
                    "the project so credentials cannot be committed accidentally.",
                    show_fallback=False,
                )
        roots = []
        if project_git_root is not None:
            roots.append(project_git_root)
        existing_parent = self.path.parent
        while not existing_parent.exists() and existing_parent != existing_parent.parent:
            existing_parent = existing_parent.parent
        destination_git_root = _git_root(existing_parent)
        if destination_git_root is not None and destination_git_root not in roots:
            roots.append(destination_git_root)
        for git_root in roots:
            self._validate_git_destination(git_root)

    def _validate_git_destination(self, git_root: Path) -> None:
        relative_path = _relative_to(self.path, git_root)
        if relative_path is None:
            return
        relative_text = relative_path.as_posix()
        tracked = subprocess.run(
            ["git", "-C", str(git_root), "ls-files", "--error-unmatch", "--", relative_text],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            check=False,
        )
        if tracked.returncode == 0:
            raise OnboardingError(
                "Refusing to write credentials to a Git-tracked file: " + str(self.path),
                show_fallback=False,
            )
        ignored = subprocess.run(
            ["git", "-C", str(git_root), "check-ignore", "--quiet", "--", relative_text],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            check=False,
        )
        if ignored.returncode != 0:
            raise OnboardingError(
                "Credential file is not ignored by Git: "
                + str(self.path)
                + ". Add it to .gitignore or choose an external --credentials-file.",
                show_fallback=False,
            )

    def has_credentials(self) -> bool:
        if not self.path.exists():
            return False
        try:
            text = self.path.read_text(encoding="utf-8")
        except OSError:
            return False
        return all(
            re.search(r"^" + re.escape(key) + r"\s*=.+$", text, re.MULTILINE)
            for key in PROPERTY_KEYS.values()
        )

    def read_credentials(self) -> Optional[Dict[str, str]]:
        if not self.path.is_file():
            return None
        try:
            text = self.path.read_text(encoding="utf-8")
        except OSError:
            return None
        values = {}
        for name, key in PROPERTY_KEYS.items():
            match = re.search(r"^" + re.escape(key) + r"\s*=\s*(.*)$", text, re.MULTILINE)
            if not match or not match.group(1).strip():
                return None
            values[name] = match.group(1).strip()
        return values

    def ensure_code_config(self, credentials: Dict[str, str]) -> None:
        self._ensure_config_ignored()
        self._validate_config_file()
        self._write_code_config(credentials)
        self.verify_code_config(credentials)

    def _validate_config_file(self) -> None:
        if self.config_path.exists():
            try:
                existing = self.config_path.read_text(encoding="utf-8")
            except OSError as exc:
                raise OnboardingError("Unable to read generated SDK config: " + str(self.config_path), show_fallback=False) from exc
            if not self._has_config_marker(existing):
                raise OnboardingError(
                    "Refusing to overwrite an existing non-Skill config: " + str(self.config_path),
                    show_fallback=False,
                )

    def _write_code_config(self, credentials: Dict[str, str]) -> None:
        package = self.package_name
        content = (
            "package " + package + ";\n\n"
            "/** " + CONFIG_MARKER + ". Do not edit or commit this file. */\n"
            "public final class SkillSdkConfig {\n"
            "    private SkillSdkConfig() {}\n\n"
            "    public static final String APP_ID = " + _java_string(credentials["appId"]) + ";\n"
            "    // APP_SECRET is the platform md5Key; never use the platform secret here.\n"
            "    public static final String APP_SECRET = " + _java_string(credentials["md5Key"]) + ";\n"
            "}\n"
        )
        _atomic_write(self.config_path, content)
        self.verify_code_config(credentials)

    def verify_code_config(self, credentials: Dict[str, str]) -> None:
        try:
            content = self.config_path.read_text(encoding="utf-8")
        except FileNotFoundError as exc:
            raise OnboardingError(
                "Generated SDK config is missing. Rerun onboarding to generate "
                "SkillSdkConfig.java before building.",
                show_fallback=False,
            ) from exc
        except OSError as exc:
            raise OnboardingError(
                "Unable to read generated SDK config: " + str(self.config_path),
                show_fallback=False,
            ) from exc

        if not self._has_config_marker(content):
            raise OnboardingError(
                "SDK config is not managed by this Skill. Rerun onboarding to generate "
                "SkillSdkConfig.java before building.",
                show_fallback=False,
            )

        app_id = self._code_config_value(content, "APP_ID")
        app_secret = self._code_config_value(content, "APP_SECRET")
        expected_app_id = _java_string(credentials["appId"])
        expected_md5_key = _java_string(credentials["md5Key"])
        platform_secret = _java_string(credentials["secret"])

        if app_id != expected_app_id:
            raise OnboardingError(
                "SkillSdkConfig.APP_ID does not match platform appId. Rerun onboarding "
                "before building.",
                show_fallback=False,
            )
        if app_secret != expected_md5_key:
            if credentials["secret"] != credentials["md5Key"] and app_secret == platform_secret:
                raise OnboardingError(
                    "SkillSdkConfig.APP_SECRET incorrectly uses platform secret; it must use "
                    "platform md5Key. Rerun onboarding before building.",
                    show_fallback=False,
                )

            raise OnboardingError(
                "SkillSdkConfig.APP_SECRET does not match platform md5Key. Rerun onboarding "
                "before building.",
                show_fallback=False,
            )

    @staticmethod
    def _has_config_marker(content: str) -> bool:
        return CONFIG_MARKER in content or any(
            marker in content for marker in LEGACY_CONFIG_MARKERS
        )

    @staticmethod
    def _code_config_value(content: str, name: str) -> Optional[str]:
        matches = re.findall(
            r"^\s*public\s+static\s+final\s+String\s+"
            + re.escape(name)
            + r"\s*=\s*(\"(?:\\.|[^\"\\])*\")\s*;\s*$",
            content,
            re.MULTILINE,
        )
        return matches[0] if len(matches) == 1 else None

    def _ensure_config_ignored(self) -> None:
        git_root = _git_root(self.project_dir)
        if git_root is not None:
            relative = _relative_to(self.config_path, git_root)
            if relative is not None:
                tracked = subprocess.run(
                    ["git", "-C", str(git_root), "ls-files", "--error-unmatch", "--", relative.as_posix()],
                    stdout=subprocess.DEVNULL,
                    stderr=subprocess.DEVNULL,
                    check=False,
                )
                if tracked.returncode == 0:
                    raise OnboardingError(
                        "Generated SDK config is Git-tracked; remove it from Git before onboarding: "
                        + str(self.config_path),
                        show_fallback=False,
                    )
                ignored = subprocess.run(
                    ["git", "-C", str(git_root), "check-ignore", "--quiet", "--", relative.as_posix()],
                    stdout=subprocess.DEVNULL,
                    stderr=subprocess.DEVNULL,
                    check=False,
                )
                if ignored.returncode == 0:
                    return
                ignore_file = git_root / ".gitignore"
                existing = ignore_file.read_text(encoding="utf-8") if ignore_file.exists() else ""
                line = relative.as_posix()
                if line not in {item.strip() for item in existing.splitlines()}:
                    prefix = "" if not existing or existing.endswith("\n") else "\n"
                    _atomic_write(ignore_file, existing + prefix + line + "\n")

    def write(self, credentials: Dict[str, str]) -> None:
        self._ensure_config_ignored()
        self._validate_config_file()
        values = {
            PROPERTY_KEYS[name]: _escape_property(credentials[name])
            for name in PROPERTY_KEYS
        }
        lines = []
        found = set()
        if self.path.exists():
            lines = self.path.read_text(encoding="utf-8").splitlines()
        updated = []
        for line in lines:
            match = re.match(r"^\s*([^#!\s:=]+)\s*[:=]", line)
            key = match.group(1) if match else None
            if key == LEGACY_ENVIRONMENT_PROPERTY:
                continue
            if key in values:
                if key not in found:
                    updated.append(key + "=" + values[key])
                    found.add(key)
                continue
            updated.append(line)
        for key, value in values.items():
            if key not in found:
                updated.append(key + "=" + value)
        _atomic_write(self.path, "\n".join(updated) + "\n")
        self._write_code_config(credentials)
        self.verify_code_config(credentials)


def _escape_property(value: str) -> str:
    return value.replace("\\", "\\\\").replace("\r", "\\r").replace("\n", "\\n")


def _java_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=True)


def _valid_password(password: str, mobile: str) -> bool:
    if not 8 <= len(password) <= 20 or password == mobile:
        return False
    categories = 0
    categories += any(character in string.ascii_letters for character in password)
    categories += any(character in string.digits for character in password)
    categories += any(character in string.punctuation for character in password)
    return categories >= 2 and all(character in string.printable and not character.isspace() for character in password)


def _mask_mobile(mobile: str) -> str:
    return mobile[:3] + "****" + mobile[-4:]


def _gradle_files(project_dir: Path):
    for root, directories, files in os.walk(str(project_dir)):
        directories[:] = [item for item in directories if item not in SKIP_DIRS]
        for name in files:
            if name in ("build.gradle", "build.gradle.kts"):
                yield Path(root) / name


def _applies_android_application_plugin(text: str) -> bool:
    if re.search(
        r"apply\s+plugin\s*:\s*[\"']com\.android\.application[\"']",
        text,
    ):
        return True
    for line in text.splitlines():
        if not re.search(
            r"\bid\s*(?:\(\s*)?[\"']com\.android\.application[\"']",
            line,
        ):
            continue
        if not re.search(r"\bapply\s+false\b", line):
            return True
    return False


def _application_id(build_file: Path) -> str:
    text = build_file.read_text(encoding="utf-8", errors="replace")
    match = re.search(
        r"(?m)^\s*applicationId\s*(?:=\s*|\(\s*)?[\"']"
        r"([A-Za-z][A-Za-z0-9_]*(?:\.[A-Za-z][A-Za-z0-9_]*)+)[\"']",
        text,
    )
    if not match:
        raise OnboardingError(
            "Could not read a literal applicationId from " + str(build_file),
            show_fallback=False,
        )
    return match.group(1)


def _application_module(project_dir: Path, module_dir: Optional[Path]) -> Path:
    if module_dir:
        candidate = module_dir.expanduser()
        if not candidate.is_absolute():
            candidate = project_dir / candidate
        candidate = candidate.resolve()
        try:
            candidate.relative_to(project_dir)
        except ValueError as exc:
            raise OnboardingError(
                "Application module must be inside the project",
                show_fallback=False,
            ) from exc
        build_files = [candidate / "build.gradle", candidate / "build.gradle.kts"]
        existing = [item for item in build_files if item.is_file()]
        if len(existing) != 1 or not _applies_android_application_plugin(
            existing[0].read_text(encoding="utf-8", errors="replace")
        ):
            raise OnboardingError(
                "The selected module does not apply com.android.application: " + str(candidate),
                show_fallback=False,
            )
        return candidate

    candidates = []
    for build_file in _gradle_files(project_dir):
        try:
            text = build_file.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        if _applies_android_application_plugin(text):
            candidates.append(build_file.parent.resolve())
    unique = sorted(set(candidates), key=str)
    if len(unique) == 1:
        return unique[0]
    if not unique:
        raise OnboardingError(
            "No Android application module was detected.",
            show_fallback=False,
        )
    raise OnboardingError(
        "Multiple Android application modules were detected. Pass --module-dir explicitly: "
        + ", ".join(str(item.relative_to(project_dir)) for item in unique),
        show_fallback=False,
    )


def _detect_package_name(project_dir: Path, module_dir: Optional[Path]) -> tuple:
    module = _application_module(project_dir, module_dir)
    build_file = module / "build.gradle"
    if not build_file.is_file():
        build_file = module / "build.gradle.kts"
    return module, _application_id(build_file)


class OnboardingFlow:
    def __init__(
        self,
        args: argparse.Namespace,
        client: OpenPlatformClient,
        store: StateStore,
        writer: CredentialsWriter,
    ) -> None:
        self.args = args
        self.client = client
        self.store = store
        self.writer = writer
        self.state = store.load()

    def run(self) -> None:
        self.writer.validate_destination()
        existing_credentials = self.writer.read_credentials()
        if self.args.check:
            print("Open platform: " + self.client.base_url)
            print("Source label: " + self.args.src)
            print("Application module: " + str(self.args.module_dir))
            print("Application package: " + self.args.package_name)
            print("Credentials file: " + str(self.writer.path))
            if existing_credentials:
                self.writer.verify_code_config(existing_credentials)
                print("SDK credential mapping is valid: APP_SECRET uses platform md5Key.")
            else:
                raise OnboardingError(
                    "Complete platform credentials are absent. Run onboarding before building.",
                    show_fallback=False,
                )
            print("Configuration is valid; no network requests were made.")
            return
        if existing_credentials:
            self.writer.ensure_code_config(existing_credentials)
            print("Credentials are already configured in " + str(self.writer.path))
            print("SDK config source: " + str(self.writer.config_path))
            return
        if not self.args.confirm:
            self._show_confirmation()
            raise OnboardingError(
                "Mutating onboarding is disabled. Rerun with --confirm to authenticate and "
                "create or reuse the application.",
                show_fallback=False,
            )

        token = self.state.get("token") if self._token_is_valid() else None
        if not token:
            token = self._authenticate()
        credentials = self._create_app_with_reauth(token)
        self.writer.write(credentials)
        self.state["appId"] = credentials["appId"]
        self.state["credentialsFile"] = str(self.writer.path)
        self.store.save(self.state)
        print("Application credentials were written to " + str(self.writer.path))
        print("SDK config source: " + str(self.writer.config_path))
        print("App ID: " + credentials["appId"])
        print("App Secret and md5Key were not printed.")

    def _show_confirmation(self) -> None:
        print("Open platform: " + self.client.base_url)
        print("Source label: " + self.args.src)
        print("Application name: " + self.args.app_name)
        print("Application package: " + self.args.package_name)
        print(
            "Rerunning with --confirm will send an SMS and may register an account "
            "and create an application."
        )

    def _token_is_valid(self) -> bool:
        try:
            expire_at = int(self.state.get("expireAt", 0))
        except (TypeError, ValueError):
            return False
        return bool(self.state.get("token")) and expire_at > int(time.time() * 1000) + 60_000

    def _mobile(self) -> str:
        title = "乐播平台账号 / HPPlay Platform Account"
        prompt = _bilingual(
            "请输入平台账号使用的 11 位手机号码。",
            "Enter the 11-digit mobile number for the platform account.",
        )
        while True:
            mobile = _input_dialog(title, prompt).strip()
            if re.fullmatch(r"\d{11}", mobile):
                if str(self.state.get("mobile") or "") != mobile:
                    for key in ("registered", "tenantId", "token", "expireAt"):
                        self.state.pop(key, None)
                self.state["mobile"] = mobile
                self.store.save(self.state)
                return mobile
            prompt = _bilingual(
                "手机号码无效，请准确输入 11 位数字。",
                "The mobile number is invalid. Enter exactly 11 digits.",
            )

    def _send_code(self, mobile: str) -> None:
        payload = {"mobile": mobile, "src": self.args.src}
        for attempt in range(2):
            try:
                self.client.post("/auth/skill/sms-send", payload)
                print("Verification code sent to " + _mask_mobile(mobile) + ".")
                return
            except ApiError as exc:
                if exc.code in SEND_RETRY_ERRORS and attempt == 0:
                    print("SMS requests are rate-limited; retrying once in 60 seconds.")
                    time.sleep(60)
                    continue
                if exc.code == 504 and attempt == 0:
                    print("SMS delivery failed; retrying once.")
                    continue
                raise self._api_failure("Unable to send a verification code", exc) from exc

    @staticmethod
    def _verification_code(rejected: bool = False) -> str:
        prompt = (
            _bilingual(
                "验证码无效，请输入最新收到的验证码。",
                "The verification code was rejected. Enter the latest verification code.",
            )
            if rejected
            else _bilingual(
                "请输入手机收到的验证码。",
                "Enter the verification code sent to your mobile number.",
            )
        )
        while True:
            code = _input_dialog(
                "乐播平台验证码 / HPPlay Verification Code", prompt, secret=True
            ).strip()
            if code:
                return code
            prompt = _bilingual(
                "验证码不能为空，请输入验证码。",
                "The verification code cannot be empty. Enter the verification code.",
            )

    @staticmethod
    def _password(mobile: str, rejected: bool = False) -> str:
        reminder = (
            _bilingual(
                "平台未接受上一次设置的密码，请设置其他密码。",
                "The platform rejected the previous password. Choose another password.",
            )
            + "\n\n"
            if rejected
            else ""
        )
        reminder += (
            _bilingual(
                "请记住平台用户名（之前输入的手机号码）和密码。后续修改应用信息时，"
                "可能需要使用它们登录。\n\n请输入新密码：8-20 个 ASCII 字符，"
                "并且至少包含两类字符。",
                "Remember this platform username (the mobile number entered earlier) and password. "
                "You may need them to sign in later when changing application information.\n\n"
                "Enter a new password containing 8-20 ASCII characters and at least two character "
                "classes.",
            )
        )
        while True:
            password = _input_dialog(
                "创建乐播平台密码 / Create HPPlay Platform Password",
                reminder,
                secret=True,
            )
            if not _valid_password(password, mobile):
                reminder = _bilingual(
                    "密码不符合要求。请使用 8-20 个 ASCII 字符，至少包含字母、数字和"
                    "标点符号中的两类，不含空白字符，且不能与手机号码相同。",
                    "The password does not meet the requirements. Use 8-20 ASCII characters, "
                    "at least two of letters, numbers, and punctuation, no whitespace, and do "
                    "not reuse the mobile number.",
                )
                continue
            reentered = _input_dialog(
                "确认乐播平台密码 / Confirm HPPlay Platform Password",
                _bilingual(
                    "请再次输入新密码进行确认。",
                    "Re-enter the new password to verify it.",
                ),
                secret=True,
            )
            if password == reentered:
                return password
            reminder = _bilingual(
                "两次输入的密码不一致，请重新输入新密码。",
                "The passwords did not match. Enter the new password again.",
            )

    def _authenticate(self) -> str:
        saved_mobile = str(self.state.get("mobile") or "")
        mobile = self._mobile()
        known_registered = bool(self.state.get("registered")) and mobile == saved_mobile
        register_login_cycle = 0
        resend_count = 0
        while resend_count < 4:
            self._send_code(mobile)
            code = self._verification_code()
            action = "login" if known_registered else "register"
            password = None
            password_rejected = False
            code_failures = 0
            while True:
                try:
                    if action == "register":
                        password = password or self._password(mobile, password_rejected)
                        password_rejected = False
                        auth_data = self.client.post(
                            "/auth/skill/register",
                            {
                                "mobile": mobile,
                                "code": code,
                                "password": password,
                                "src": self.args.src,
                            },
                        )
                        known_registered = True
                    else:
                        auth_data = self._login(mobile, code)
                    return self._save_auth(auth_data, mobile)
                except ApiError as exc:
                    if exc.code == 510:
                        code_failures += 1
                        if code_failures >= 5:
                            raise OnboardingError("Verification code failed five times.") from exc
                        code = self._verification_code(rejected=True)
                        continue
                    if exc.code in CODE_EXPIRED_ERRORS or exc.code == 1104:
                        resend_count += 1
                        known_registered = known_registered or action == "login"
                        print("The verification session expired; requesting a new code in 60 seconds.")
                        time.sleep(60)
                        break
                    if action == "register" and exc.code == 302:
                        password = None
                        password_rejected = True
                        continue
                    if action == "register" and exc.code == 1101:
                        known_registered = True
                        action = "login"
                        password = None
                        print(
                            "该手机号码已注册，将使用同一验证码进入登录流程。\n"
                            "This mobile number is already registered; continuing to login "
                            "with the same verification code."
                        )
                        continue
                    if action == "login" and exc.code == 1105:
                        register_login_cycle += 1
                        if register_login_cycle > 1:
                            raise OnboardingError(
                                "The platform alternated between registered and unregistered states."
                            ) from exc
                        known_registered = False
                        action = "register"
                        password = None
                        password_rejected = False
                        continue
                    if exc.code == 508:
                        raise OnboardingError("The platform account is disabled; contact support.") from exc
                    raise self._api_failure("Authentication failed", exc) from exc
        raise OnboardingError("Too many expired verification sessions.")

    def _login(self, mobile: str, code: str) -> Dict[str, Any]:
        try:
            return self.client.post(
                "/auth/skill/login",
                {"mobile": mobile, "code": code},
            )
        except ApiError as exc:
            if exc.code != 1103:
                raise
            identity = str(exc.data.get("identity") or "")
            accounts = exc.data.get("accountList")
            if not identity or not isinstance(accounts, list) or not accounts:
                raise OnboardingError("The platform returned an invalid account selection response.") from exc
            account = self._select_account([str(value) for value in accounts])
            return self.client.post(
                "/auth/skill/login",
                {
                    "mobile": mobile,
                    "account": account,
                    "identity": identity,
                },
            )

    @staticmethod
    def _select_account(accounts: list) -> str:
        choices = "\n".join(
            str(index) + ". " + account for index, account in enumerate(accounts, start=1)
        )
        title = "选择乐播平台账号 / Select HPPlay Platform Account"
        prompt = _bilingual(
            "检测到多个账号，请输入账号序号：",
            "Multiple accounts are available. Enter an account number:",
        ) + "\n\n" + choices
        while True:
            choice = _input_dialog(title, prompt).strip()
            try:
                index = int(choice)
                if 1 <= index <= len(accounts):
                    return accounts[index - 1]
            except ValueError:
                pass
            prompt = _bilingual(
                "请输入列表中的账号序号。",
                "Choose one of the listed account numbers.",
            ) + "\n\n" + choices

    def _save_auth(self, data: Dict[str, Any], mobile: str) -> str:
        token = str(data.get("token") or "")
        if not token:
            raise OnboardingError("Authentication succeeded without a token.")
        self.state.update(
            {
                "mobile": mobile,
                "registered": True,
                "tenantId": data.get("tenantId"),
                "token": token,
                "expireAt": data.get("expireAt"),
            }
        )
        self.store.save(self.state)
        return token

    def _create_app_with_reauth(self, token: str) -> Dict[str, str]:
        reauthenticated = False
        corrected_type = False
        while True:
            try:
                data = self.client.post(
                    "/developer/skill/app/create",
                    {
                        "name": self.args.app_name,
                        "packageName": self.args.package_name,
                        "platformType": 1,
                        "vipType": 0,
                        "terminalType": 1,
                        "businessType": 1,
                    },
                    token=token,
                )
                return self._credentials(data)
            except ApiError as exc:
                if exc.code == 1123:
                    return self._credentials(exc.data)
                if exc.code in AUTH_ERROR_CODES and not reauthenticated:
                    self.state.pop("token", None)
                    self.state.pop("expireAt", None)
                    self.store.save(self.state)
                    token = self._authenticate()
                    reauthenticated = True
                    continue
                if exc.code == 1122 and not corrected_type:
                    corrected_type = True
                    continue
                if exc.code == 1121:
                    raise OnboardingError(
                        "The public-SDK application limit has been reached. Reuse an existing "
                        "App ID or remove an unused application in the console.",
                        show_fallback=False,
                    ) from exc
                if exc.code == 1124:
                    raise OnboardingError(
                        "This package already belongs to an application that this account cannot "
                        "view. Ask the tenant administrator for its credentials or use another package.",
                        show_fallback=False,
                    ) from exc
                if exc.code == 1120:
                    raise OnboardingError("The platform account is disabled; contact support.") from exc
                raise self._api_failure("Application creation failed", exc) from exc

    @staticmethod
    def _credentials(data: Dict[str, Any]) -> Dict[str, str]:
        credentials = {
            "appId": str(data.get("appId") or ""),
            "secret": str(data.get("secret") or ""),
            "md5Key": str(data.get("md5Key") or ""),
        }
        if not all(credentials.values()):
            raise OnboardingError("The platform response did not contain complete credentials.")
        return credentials

    @staticmethod
    def _api_failure(context: str, exc: ApiError) -> OnboardingError:
        details = exc.message
        if exc.code is not None:
            details += " (errorCode " + str(exc.code) + ")"
        elif exc.http_status is not None:
            details += " (HTTP " + str(exc.http_status) + ")"
        return OnboardingError(context + ": " + details)


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Obtain Android sender SDK credentials using modal dialogs."
    )
    parser.add_argument("--project-dir", required=True, type=Path, help="Android project root")
    parser.add_argument("--app-name", required=True, help="Application name, at most 30 characters")
    parser.add_argument(
        "--module-dir",
        type=Path,
        help="Application module, relative to the project root; required only when ambiguous",
    )
    parser.add_argument(
        "--src",
        default=DEFAULT_SRC,
        help="Optional source label; defaults to android-sender-sdk (at most 32 characters)",
    )
    parser.add_argument(
        "--credentials-file",
        type=Path,
        help="Ignored project file or a path outside the project; defaults to local.properties",
    )
    parser.add_argument("--check", action="store_true", help="Validate inputs without network calls")
    parser.add_argument(
        "--confirm",
        action="store_true",
        help="Enable authentication and application creation after read-only preflight",
    )
    parser.add_argument("--reset-state", action="store_true", help="Clear resumable auth state first")
    args = parser.parse_args()

    args.project_dir = args.project_dir.expanduser().resolve()
    if not args.project_dir.is_dir():
        parser.error("--project-dir must be an existing directory")
    if not 1 <= len(args.app_name) <= 30:
        parser.error("--app-name must contain 1-30 characters")
    if not 1 <= len(args.src) <= 32:
        parser.error("--src must contain 1-32 characters")
    try:
        args.module_dir, args.package_name = _detect_package_name(
            args.project_dir,
            args.module_dir,
        )
    except (OSError, OnboardingError) as exc:
        parser.error(str(exc))
    return args


def main() -> int:
    args = _parse_args()
    base_url = OPEN_PLATFORM_BASE_URL
    store = StateStore(args.package_name, args.src, base_url)
    if args.reset_state:
        store.clear()
    writer = CredentialsWriter(
        args.project_dir,
        args.module_dir,
        args.package_name,
        args.credentials_file,
    )
    flow = OnboardingFlow(args, OpenPlatformClient(base_url), store, writer)
    try:
        flow.run()
        return 0
    except (OnboardingError, ApiError) as exc:
        print("Onboarding failed: " + str(exc), file=sys.stderr)
        show_fallback = not isinstance(exc, OnboardingError) or exc.show_fallback
        if show_fallback:
            fallback = (base_url + FALLBACK_PATH).format(src=parse.quote(args.src, safe=""))
            print("Complete onboarding in a browser: " + fallback, file=sys.stderr)
            print(
                "Prepare the mobile number, application name, and package name.",
                file=sys.stderr,
            )
        return 2


if __name__ == "__main__":
    sys.exit(main())
