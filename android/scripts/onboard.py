class ApiError(Exception):
    def __init__(
        self,
        code: Optional[int],
        message: str,
        data: Optional[Dict[str, Any]] = None,
        http_status: Optional[int] = None,
    ) -> None:
        super().__init__(message)
        self.code = code
        self.message = message
        self.data = data or {}
        self.http_status = http_status


