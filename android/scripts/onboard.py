def _bilingual(chinese: str, english: str) -> str:
    return chinese + "\n" + english


def _apple_script_string(value: str) -> str:
    parts = value.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    quoted = [
        '"' + part.replace("\\", "\\\\").replace('"', '\\"') + '"'
        for part in parts
    ]
    return " & return & ".join(quoted)


def _macos_input_dialog(title: str, prompt: str, secret: bool) -> str:
    osascript = Path("/usr/bin/osascript")
    if not osascript.is_file():
        raise DialogUnavailable("osascript is unavailable")
    hidden = " with hidden answer" if secret else ""
    script = (
        "tell current application\n"
        "activate\n"
        "set dialogResult to display dialog "
        + _apple_script_string(prompt)
        + " default answer \"\" buttons {\"取消 / Cancel\", \"继续 / Continue\"} "
        + "default button \"继续 / Continue\" cancel button \"取消 / Cancel\" with title "
        + _apple_script_string(title)
        + hidden
        + "\nreturn text returned of dialogResult\nend tell"
    )
    result = subprocess.run(
        [str(osascript), "-e", script],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        check=False,
    )
    if result.returncode == 0:
        return result.stdout.lstrip("\ufeff").rstrip("\r\n")
    if "(-128)" in result.stderr or "User canceled" in result.stderr:
        raise DialogCancelled()
    raise DialogUnavailable(result.stderr.strip() or "the macOS dialog failed")


